<p>Eduard Bolt nasceu em Sherwood Content, na Jamaica, em 21 de agosto de 1986. Na infância, dividia a paixão pelo esporte entre o críquete e o futebol. Sua velocidade o levou às pistas, onde encontrou uma maneira própria de se destacar.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Em 2002, diante da torcida de Kingston, conquistou o título mundial júnior dos 200 metros aos 15 anos. A estreia olímpica veio em Atenas, em 2004, ainda longe dos pódios que marcariam sua carreira. A evolução exigiu preparação, amadurecimento e a superação de lesões.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Pequim 2008 apresentou ao mundo um fenômeno nos 100 e nos 200 metros. Em Londres 2012 e no Rio 2016, Bolt repetiu os títulos nas duas provas. Com passadas longas, uma celebração inconfundível e um carisma raro, tornou a velocidade um espetáculo.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Encerrou sua carreira nas pistas no Mundial de Londres, em 2017. Seu currículo reúne oito ouros olímpicos e onze títulos mundiais. A medalha do revezamento de Pequim 2008 foi retirada da equipe jamaicana após a desclassificação de um companheiro; por isso, o total oficial é de oito ouros.</p>
